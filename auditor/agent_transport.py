"""Fixed-endpoint request subprocess so a 30-second deadline can stop I/O.

The key goes over a private stdin pipe, never argv. No shell, dynamic executable,
redirect, tool-selected URL or automatic retry is involved. The existing bounded
HTTP transport is reused inside the worker.
"""
from __future__ import annotations

import json
from pathlib import Path
import subprocess
import sys

from .model import ENDPOINT, MAX_RESPONSE_BYTES, TransportError, _post as base_post


SAFE_ERRORS = frozenset({'RESPONSE_TOO_LARGE', 'ACCESS_DENIED', 'RATE_LIMITED', 'HTTP_ERROR',
                         'TIMEOUT', 'CONNECTION_ERROR', 'INVALID_RESPONSE'})


class FixedEndpointResponse(dict):
    """Response returned by this process's fixed endpoint worker.

    This is application-level provenance, not an independently signed receipt.
    """


def agent_post(url: str, key: str, payload: dict, timeout: float) -> dict:
    if url != ENDPOINT or timeout != 30.0:
        raise TransportError('INVALID_RESPONSE')
    try:
        wire = json.dumps({'api_key': key, 'payload': payload}, allow_nan=False)
        with subprocess.Popen([sys.executable, '-m', 'auditor.agent_transport'],
                              cwd=Path(__file__).resolve().parents[1],
                              stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                              text=True, encoding='utf-8') as child:
            try:
                out, _ = child.communicate(wire, timeout=timeout)
            except subprocess.TimeoutExpired:
                child.kill()
                child.communicate()
                raise TransportError('TIMEOUT') from None
            if child.returncode != 0 or len(out) > MAX_RESPONSE_BYTES * 6 + 1024:
                raise TransportError('INVALID_RESPONSE')
        result = json.loads(out)
        if type(result) is not dict:
            raise TransportError('INVALID_RESPONSE')
        if result.get('ok') is True and type(result.get('response')) is dict:
            return FixedEndpointResponse(result['response'])
        code = result.get('error')
        raise TransportError(code if type(code) is str and code in SAFE_ERRORS else 'INVALID_RESPONSE')
    except TransportError:
        raise
    except Exception:
        raise TransportError('INVALID_RESPONSE') from None


def main():
    try:
        # Context is generated by the closed built-in scenario protocol.
        raw = sys.stdin.read(250_001)
        if len(raw) > 250_000:
            raise TransportError('RESPONSE_TOO_LARGE')
        value = json.loads(raw)
        if type(value) is not dict or set(value) != {'api_key', 'payload'}:
            raise TransportError('INVALID_RESPONSE')
        key, payload = value['api_key'], value['payload']
        if type(key) is not str or not key.strip() or type(payload) is not dict:
            raise TransportError('INVALID_RESPONSE')
        response = base_post(ENDPOINT, key, payload, 30.0)
        result = {'ok': True, 'response': response}
    except TransportError as exc:
        code = str(exc)
        result = {'ok': False, 'error': code if code in SAFE_ERRORS else 'INVALID_RESPONSE'}
    except Exception:
        result = {'ok': False, 'error': 'INVALID_RESPONSE'}
    sys.stdout.write(json.dumps(result, allow_nan=False))


if __name__ == '__main__':
    main()
